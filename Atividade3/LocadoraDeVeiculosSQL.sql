create table cliente (
  id_cliente bigint generated by default as identity primary key,
  nome varchar(100) not null,
  cpf varchar(11) unique not null,
  idade int not null check (idade >= 18)
);



create table locacao(
  id_locacao bigint generated by default as identity primary key,
  km_rodados numeric(10,2) not null default 0.0
);

alter table locacao
  add column tem_seguro boolean not null default false;

alter table locacao
  add constraint ck_km_rodados
  check (km_rodados >= 0.0);



create table cliente_locacao (
  id_cliente_locacao bigint generated by default as identity primary key,
  id_locacao bigint not null,

  constraint fk_locacao
    foreign key (id_locacao)
    references locacao(id_locacao)
);

alter table cliente_locacao
  add column id_cliente bigint not null;

alter table cliente_locacao
  add constraint fk_cliente
  foreign key (id_cliente)
  references cliente(id_cliente);




create table carro (
  id_carro bigint generated by default as identity primary key,
  modelo varchar(60) not null,
  placa varchar(7) unique not null,
  preco_por_dia numeric(10,2) not null,
  kilometragem numeric(10,2) not null default 0.0,
  id_locacao bigint,

  constraint fk_id_locacao
    foreign key (id_locacao)
    references locacao(id_locacao)
);