create table cliente (
  id_cliente bigint generated by default as identity primary key,
  nome varchar(100) not null,
  telefone varchar(16) not null,
  email varchar(100)
);



create table veiculo (
  id_veiculo bigint generated by default as identity primary key,
  placa varchar(7) not null,
  modelo varchar(60) not null,
  ano int not null,
  quilometragem numeric(10,2) not null default 0.0,
  id_cliente bigint,

  constraint fk_id_cliente
    foreign key (id_cliente)
    references cliente(id_cliente)
);



create table peca (
  id_peca bigint generated by default as identity primary key,
  descricao varchar(255),
  fabricante varchar(60) not null,
  valor_referencia numeric(10,2) not null default 0.0
);



create table funcionario (
  id_funcionario bigint generated by default as identity primary key,
  nome varchar(100) not null,
  data_admissao date not null
);



create table atendente (
  id_atendente bigint generated by default as identity primary key,
  ramal int not null,
  id_funcionario bigint not null,

  constraint fk_id_funcionario
    foreign key (id_funcionario)
    references funcionario(id_funcionario)
);



create table mecanico (
  id_mecanico bigint generated by default as identity primary key,
  especialidade varchar(30) not null,
  id_funcionario bigint not null,

  constraint fk_id_funcionario
    foreign key (id_funcionario)
    references funcionario(id_funcionario)
);



create table servico (
  id_servico bigint generated by default as identity primary key,
  tipo_servico varchar(40) not null,
  valor_referencia numeric(10,2) not null default 0.0,
  descricao varchar(256)
);



create table servico_mecanico (
  id_servico_mecanico bigint generated by default as identity primary key,
  id_servico bigint not null,
  id_mecanico bigint not null,

  constraint fk_id_servico
    foreign key (id_servico)
    references servico(id_servico),
  
  constraint fk_id_mecanico
    foreign key (id_mecanico)
    references mecanico(id_mecanico)
);



create table ordem_servico (
  id_ordem_servico bigint generated by default as identity primary key,
  data_inicio date not null,
  data_fim date,
  status varchar(10),
  id_veiculo bigint not null,

  constraint fk_id_veiculo
    foreign key (id_veiculo)
    references veiculo(id_veiculo)
);



create table ordem_servico_servico (
  id_ordem_servico_servico bigint generated by default as identity primary key,
  id_ordem_servico bigint not null,
  id_servico bigint not null,

  constraint fk_id_ordem_servico
    foreign key (id_ordem_servico)
    references ordem_servico(id_ordem_servico),

  constraint fk_id_servico
    foreign key (id_servico)
    references servico(id_servico)
);



create table ordem_servico_peca (
  id_ordem_servico_peca bigint generated by default as identity primary key,
  id_ordem_servico bigint not null,
  id_peca bigint not null,

  constraint fk_id_ordem_servico
    foreign key (id_ordem_servico)
    references ordem_servico(id_ordem_servico),

  constraint fk_id_peca
    foreign key (id_peca)
    references peca(id_peca)
);